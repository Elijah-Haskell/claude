// The "Certificate of completion": a PDF saved to the matter's documents beside the signed
// document. It records what was signed (by hash), who signed, how they consented, and the
// full audit trail. The signed document itself is not altered.

import { PdfBuilder } from "./pdf.ts";
import type { Png } from "./png.ts";

type Row = Record<string, any>;

const KIND_LABEL: Record<string, string> = {
  sent: "Sent for signature",
  resent: "Sent again (new link)",
  opened: "Signing page opened",
  document_viewed: "Document opened by signer",
  consented: "Agreed to sign electronically",
  signed: "Signed",
  declined: "Asked to sign on paper / declined",
  cancelled: "Cancelled by the firm",
  certificate_created: "Certificate created",
};

export function central(iso: string): string {
  try {
    return new Intl.DateTimeFormat("en-US", {
      timeZone: "America/Chicago",
      year: "numeric",
      month: "short",
      day: "numeric",
      hour: "numeric",
      minute: "2-digit",
      second: "2-digit",
      timeZoneName: "short",
    }).format(new Date(iso));
  } catch {
    return iso;
  }
}

export function buildCertificate(input: {
  firmName: string;
  request: Row;
  events: Row[];
  signature: Png | null;
  chainIntact: boolean;
  generatedAt: Date;
}): Buffer {
  const r = input.request;
  const pdf = new PdfBuilder({
    title: `Certificate of completion - ${r.doc_name}`,
    footer: (n, t) => `Lawdesk signature request ${r.id}  ·  Certificate of completion  ·  Page ${n} of ${t}`,
  });
  pdf.para(input.firmName || "Law firm", { font: "Times-Roman", size: 11, gray: 0.35, gap: 2 });
  pdf.para("Certificate of Completion", { font: "Times-Bold", size: 22, gap: 2 });
  pdf.para("Electronic signature record", { font: "Times-Italic", size: 12, gray: 0.3, gap: 10 });

  pdf.heading("Document");
  pdf.field("Name", r.doc_name);
  pdf.field("Version signed", `Version ${r.version}`);
  pdf.field("SHA-256 when sent", r.doc_sha256);
  pdf.field("SHA-256 when signed", r.signed_doc_sha256 ?? "");
  pdf.field("Unchanged", r.signed_doc_sha256 === r.doc_sha256 ? "Yes. The file signed is identical to the file sent." : "NO. The file changed after it was sent.");

  pdf.heading("Signer");
  pdf.field("Name (as sent)", r.signer_name);
  pdf.field("Email", r.signer_email ?? "");
  pdf.field("Name typed to sign", r.typed_name ?? "");
  pdf.field("Signed", r.signed_at ? `${central(r.signed_at)}  (${r.signed_at} UTC)` : "");
  pdf.field("Signature", r.signature_kind === "drawn" ? "Drawn by the signer (below)" : "Typed name adopted as signature");
  if (input.signature) pdf.image(input.signature, 260, 90, pdf.margin + 150);
  else if (r.typed_name) pdf.para(r.typed_name, { font: "Times-Italic", size: 20, indent: 150, gap: 6 });
  if (r.signature_sha256) pdf.field("Signature image SHA-256", r.signature_sha256);

  pdf.heading("Consent to sign electronically");
  pdf.field("Agreed", r.consent_at ? `${central(r.consent_at)}  (${r.consent_at} UTC)` : "");
  pdf.field("Disclosure version", r.consent_version ?? "");
  pdf.field("Disclosure SHA-256", r.consent_sha256 ?? "");
  pdf.para("The full disclosure the signer agreed to is reproduced at the end of this certificate.", { size: 9, gray: 0.35 });

  pdf.heading("Audit trail");
  pdf.para(
    input.chainIntact
      ? "Each entry below is linked to the one before it by a SHA-256 hash. The chain was checked when this certificate was made and is intact."
      : "WARNING: the audit trail hash chain did not verify when this certificate was made.",
    { size: 9, gray: 0.35, gap: 6 },
  );
  for (const e of input.events) {
    pdf.para(`${central(e.at)}  —  ${KIND_LABEL[e.kind] ?? e.kind}`, { font: "Helvetica-Bold", size: 9.5, gap: 1 });
    const bits = [e.ip ? `IP address ${e.ip}` : null, e.user_agent ? `Browser: ${e.user_agent}` : null, e.detail ? detailText(e.detail) : null].filter(Boolean);
    if (bits.length) pdf.para(bits.join("   ·   "), { size: 8.5, indent: 12, gray: 0.25, gap: 1 });
    pdf.para(`Entry hash ${e.hash}`, { size: 7.5, indent: 12, gray: 0.5, gap: 5 });
  }

  pdf.heading("Disclosure shown to the signer");
  for (const p of String(r.consent_text ?? "").split(/\n\n/)) pdf.para(p, { font: "Times-Roman", size: 10, gap: 6 });

  pdf.y -= 8;
  pdf.para(
    `Generated by Lawdesk on ${central(input.generatedAt.toISOString())}. This certificate records how the document above was signed electronically. Keep it with the document.`,
    { size: 8.5, gray: 0.4 },
  );
  return pdf.build(input.generatedAt);
}

function detailText(detail: string): string {
  try {
    const d = JSON.parse(detail);
    return Object.entries(d)
      .filter(([, v]) => v !== null && v !== undefined && v !== "")
      .map(([k, v]) => `${k.replace(/_/g, " ")}: ${v}`)
      .join(", ");
  } catch {
    return detail;
  }
}
