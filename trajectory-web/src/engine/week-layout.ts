// ── What the grid draws ───────────────────────────────────────

/**
 * The planner's own 15-minute "Transition" after each class (lib/scheduler.ts generateWeekSchedule, regenerated by
 * every plan): busy time for the planner only. A "buffer" event the student made (Ask AI can create one, e.g. a
 * commute) is NOT one: it is shown like any other event, so it can be seen, edited and deleted.
 */
export function isPlannerTransition(block: Pick<ScheduleBlock, "type"> & { title?: string }): boolean {
  return block.type === "buffer" && block.title === "Transition";
}

/**
 * Does a block appear on the Week grid (and Today's timeline)? Sleep is drawn as bands, and the planner's transitions
 * are busy time only: neither is a block to tap or to count.
 */
export function showsOnWeekGrid(block: Pick<ScheduleBlock, "type"> & { title?: string }): boolean {
  return block.type !== "sleep" && !isPlannerTransition(block);
}

/**
 * A study session the plan may still move when something changes (drawn dashed on Week and Today): auto-planned and
 * not yet kept by the student. "Keep this time" (ACCEPT_BLOCK), an edit, a start or a lock makes it kept.
 */
export function isFlexibleSession(block: Pick<ScheduleBlock, "type" | "accepted" | "completionStatus">): boolean {
  return block.type === "study" && !block.accepted && block.completionStatus === "pending";
}

// ── Touch areas ───────────────────────────────────────────────

export interface TouchFrame {
  top: number;
  height: number;
  left: number;
  width: number;
}

export interface VerticalSlop {
  top: number;
  bottom: number;
}

/**
 * Vertical hitSlop for the drawn blocks of one day column, so each can be tapped over at least `minTouch` points
 * without reaching into a neighbour's touch area: a block grows into the free space above and below it (a gap it
 * shares with the block on the other side is split half and half) and never past the top or bottom of the grid.
 * Only blocks that overlap horizontally are neighbours (blocks in other lanes are beside it, not above or below).
 * Widths are left alone: a day column is as wide as the screen allows.
 */
export function verticalTouchSlops(frames: readonly TouchFrame[], gridHeight: number, minTouch = 44): VerticalSlop[] {
  return frames.map((frame, index) => {
    const need = Math.max(0, minTouch - frame.height);
    if (need === 0) return { top: 0, bottom: 0 };
    const bottomEdge = frame.top + frame.height;
    let roomAbove = Math.max(0, frame.top);
    let roomBelow = Math.max(0, gridHeight - bottomEdge);
    frames.forEach((other, otherIndex) => {
      if (otherIndex === index) return;
      if (other.left >= frame.left + frame.width || frame.left >= other.left + other.width) return;
      const otherBottom = other.top + other.height;
      if (otherBottom <= frame.top) roomAbove = Math.min(roomAbove, (frame.top - otherBottom) / 2);
      else if (other.top >= bottomEdge) roomBelow = Math.min(roomBelow, (other.top - bottomEdge) / 2);
      else if (other.top + other.height / 2 < frame.top + frame.height / 2) roomAbove = 0;
      else roomBelow = 0;
    });
    let up = Math.min(roomAbove, need / 2);
    let down = Math.min(roomBelow, need / 2);
    // Whatever one side cannot take goes to the other side, as far as it has room.
    const rest = need - up - down;
    if (rest > 0) {
      const extraDown = Math.min(roomBelow - down, rest);
      down += extraDown;
      up += Math.min(roomAbove - up, rest - extraDown);
    }
    return { top: Math.floor(up), bottom: Math.floor(down) };
  });
}

// ── Overlap lanes ─────────────────────────────────────────────

export interface TimedItem {
  startTime: string; // "HH:MM"
  endTime: string;   // "HH:MM"
}

export interface LaidOutItem<T> {
  block: T;
  /** 0-based lane inside its cluster of overlapping items. */
  lane: number;
  /** Number of lanes the whole cluster needs: the item is drawn 1/laneCount of the column wide. */
  laneCount: number;
}

export interface LayoutOptions {
  /**
   * Blocks are drawn at least this tall, so a short block visually covers more time than it lasts.
   * Pass the pixel minimum converted to minutes to keep such blocks from hiding a neighbour.
   */
  minDurationMinutes?: number;
}

/**
 * Sweep-line lane assignment for one day. Items that overlap (directly or through a chain of overlaps)
 * form a cluster; inside a cluster each item takes the first lane that is free at its start, so a
 * cluster uses as few lanes as its busiest moment needs. Touching items (one ends exactly when the next
 * starts) do not overlap. The result is in the same order as the input.
 */
export function layoutDayBlocks<T extends TimedItem>(blocks: readonly T[], options: LayoutOptions = {}): LaidOutItem<T>[] {
  const minDuration = Math.max(1, options.minDurationMinutes ?? 0);
  const spans = blocks.map((block, index) => {
    const start = Math.max(0, timeToMinutes(block.startTime));
    const rawEnd = timeToMinutes(block.endTime);
    const end = Math.max(rawEnd > start ? rawEnd : start, start + minDuration);
    return { index, start, end };
  });
  const order = [...spans].sort((a, b) => a.start - b.start || b.end - a.end || a.index - b.index);

  const result = new Array<LaidOutItem<T>>(blocks.length);
  let cluster: Array<{ index: number; lane: number }> = [];
  let laneEnds: number[] = [];
  let clusterEnd = -Infinity;

  const flush = () => {
    for (const member of cluster) {
      result[member.index] = { block: blocks[member.index]!, lane: member.lane, laneCount: laneEnds.length };
    }
    cluster = [];
    laneEnds = [];
    clusterEnd = -Infinity;
  };

  for (const span of order) {
    if (cluster.length > 0 && span.start >= clusterEnd) flush();
    let lane = laneEnds.findIndex((end) => end <= span.start);
    if (lane === -1) lane = laneEnds.length;
    laneEnds[lane] = span.end;
    cluster.push({ index: span.index, lane });
    clusterEnd = Math.max(clusterEnd, span.end);
  }
  flush();
  return result;
}

/** Horizontal placement of a lane inside a day column (`inset` at both edges, `gap` between lanes). */
export function laneFrame(lane: number, laneCount: number, columnWidth: number, inset = 1, gap = 1): { left: number; width: number } {
  const count = Math.max(1, laneCount);
  const usable = Math.max(1, columnWidth - inset * 2);
  const width = Math.max(1, (usable - gap * (count - 1)) / count);
  return { left: inset + lane * (width + gap), width };
}

// ── Visible hour range ────────────────────────────────────────

export interface HourRange {
  /** First hour shown (0-23). */
  startHour: number;
  /** Hour at the bottom edge of the grid (1-24). */
  endHour: number;
}

export const DEFAULT_HOUR_RANGE: HourRange = { startHour: 6, endHour: 23 };

export interface RangeItem extends TimedItem {
  type?: BlockType | string;
}

/**
 * The hours the grid shows: at least 06:00-23:00, widened to fit every item in the visible week
 * (an 05:30 lab, a 23:30 shift). Sleep blocks never widen it: they are drawn as clipped bands.
 * An item that runs past midnight is clipped at 24:00.
 */
export function computeVisibleHourRange(items: readonly RangeItem[], base: HourRange = DEFAULT_HOUR_RANGE): HourRange {
  let startHour = base.startHour;
  let endHour = base.endHour;
  for (const item of items) {
    if (item.type === "sleep") continue;
    const start = Math.max(0, timeToMinutes(item.startTime));
    const rawEnd = timeToMinutes(item.endTime);
    const end = rawEnd > start ? Math.min(rawEnd, MINUTES_PER_DAY) : MINUTES_PER_DAY;
    startHour = Math.min(startHour, Math.floor(start / 60));
    endHour = Math.max(endHour, Math.ceil(end / 60));
  }
  startHour = Math.max(0, Math.min(startHour, 23));
  endHour = Math.min(24, Math.max(endHour, startHour + 1));
  return { startHour, endHour };
}

/** "6am", "12pm", "11pm", "12am" (hour 0 and hour 24). */
export function hourLabel(hour: number): string {
  const h = ((hour % 24) + 24) % 24;
  if (h === 0) return "12am";
  if (h === 12) return "12pm";
  return h < 12 ? `${h}am` : `${h - 12}pm`;
}

export function gridHeight(range: HourRange, hourHeight: number): number {
  return (range.endHour - range.startHour) * hourHeight;
}

/** Pixel offset of a minute-of-day inside the grid. */
export function minutesToY(minutes: number, range: HourRange, hourHeight: number): number {
  return ((minutes - range.startHour * 60) / 60) * hourHeight;
}

/** Top / height of a block in the grid (never shorter than `minHeight`; clipped to the grid's top edge). */
export function blockFrame(startTime: string, endTime: string, range: HourRange, hourHeight: number, minHeight = 18): { top: number; height: number } {
  const start = timeToMinutes(startTime);
  const rawEnd = timeToMinutes(endTime);
  const end = rawEnd > start ? Math.min(rawEnd, MINUTES_PER_DAY) : MINUTES_PER_DAY;
  const top = Math.max(0, minutesToY(start, range, hourHeight));
  const bottom = minutesToY(end, range, hourHeight);
  return { top, height: Math.max(bottom - top, minHeight) };
}

/** Y of the current-time line, or null when "now" is outside the visible hours. */
export function currentTimeY(nowMinutes: number, range: HourRange, hourHeight: number): number | null {
  if (nowMinutes < range.startHour * 60 || nowMinutes > range.endHour * 60) return null;
  return minutesToY(nowMinutes, range, hourHeight);
}

/** Scroll offset that puts `nowMinutes` about `lead` pixels below the top (now is clamped into the grid). */
export function scrollTargetForNow(nowMinutes: number, range: HourRange, hourHeight: number, lead = 120): number {
  const clamped = Math.max(range.startHour * 60, Math.min(nowMinutes, range.endHour * 60));
  return Math.max(0, minutesToY(clamped, range, hourHeight) - lead);
}

export interface SleepLike {
  date: string;
  startTime: string;
  endTime: string;
}

/**
 * Sleep as shaded bands for one day column, clipped to the visible hours. A night that starts before
 * midnight (23:00 -> 07:00) contributes its evening to the day it starts on and its morning to the next day.
 */
export function sleepBandsForDate(dateKey: string, sleepBlocks: readonly SleepLike[], range: HourRange): Array<{ startMinutes: number; endMinutes: number }> {
  const lo = range.startHour * 60;
  const hi = range.endHour * 60;
  const bands: Array<{ startMinutes: number; endMinutes: number }> = [];
  const push = (start: number, end: number) => {
    const s = Math.max(start, lo);
    const e = Math.min(end, hi);
    if (e > s) bands.push({ startMinutes: s, endMinutes: e });
  };
  for (const sleep of sleepBlocks) {
    const start = timeToMinutes(sleep.startTime);
    const end = timeToMinutes(sleep.endTime);
    const overnight = end <= start;
    if (sleep.date === dateKey) push(start, overnight ? MINUTES_PER_DAY : end);
    if (overnight && addDaysToKey(sleep.date, 1) === dateKey) push(0, end);
  }
  return bands.sort((a, b) => a.startMinutes - b.startMinutes);
}

// ── Course labels and spoken descriptions ─────────────────────

const SMALL_WORDS = new Set(["a", "an", "and", "at", "for", "in", "of", "on", "the", "to", "with"]);
const TRAILING_NUMERAL = /^(?:[ivx]{1,4}|\d{1,2})$/i;
const COURSE_CODE = /\b([A-Za-z]{2,5})[\s-]?(\d{2,4}[A-Za-z]?)\b/;

/** Four-letter cuts, and initials, that spell something a student would not want on their calendar. */
const AWKWARD_CUTS = new Set(["ANAL", "ARSE", "ASSE", "BOOB", "BUTT", "COCK", "CRAP", "CUNT", "DAMN", "DICK", "DUMB", "DYKE", "FAGG", "FUCK", "HELL", "HOMO", "JERK", "JIZZ", "KIKE", "NAZI", "PISS", "POOP", "PORN", "PUSS", "RAPE", "SHIT", "SLUT", "SPIC", "SUCK", "TITS", "TWAT", "WANK"]);
const AWKWARD_INITIALS = new Set(["ASS", "CUM", "FAG", "FUK", "KKK", "TIT"]);

/**
 * One word made short for a tag or a narrow block, in capitals: five letters or fewer are kept whole ("Art" ->
 * "ART"), a longer word is cut to its first four, the way course codes shorten a subject ("Calculus" -> "CALC").
 * Where that cut spells something else ("Analysis", "Assembly", "Cocktail"), the word loses its vowels and doubled
 * letters after the first letter instead ("ANLY", "ASMB", "CKTL").
 */
export function shortWord(word: string): string {
  const upper = word.toUpperCase();
  if (upper.length <= 5) return upper;
  const cut = upper.slice(0, 4);
  if (!AWKWARD_CUTS.has(cut)) return cut;
  const skeleton = (upper[0] + upper.slice(1).replace(/[AEIOU]/g, "")).replace(/(.)\1+/g, "$1");
  return skeleton.slice(0, 4);
}

/**
 * A short label that fits a small tag or a narrow block, always in capitals: the course code when the name has one
 * ("CHEM 101 - General Chemistry" -> "CHEM 101"), otherwise initials ("Organic Chemistry II" -> "OC II"), and for a
 * one-word name the word made short ("Calculus II" -> "CALC II", "Statistics" -> "STAT": shortWord above).
 * Initials that spell something else fall back to the first word made short.
 */
export function courseShortName(name: string): string {
  const trimmed = name.trim();
  if (!trimmed) return "";
  const code = COURSE_CODE.exec(trimmed);
  if (code) return `${code[1]!.toUpperCase()} ${code[2]!.toUpperCase()}`;

  const words = trimmed.split(/[^A-Za-z0-9]+/).filter(Boolean);
  let suffix = "";
  if (words.length > 1 && TRAILING_NUMERAL.test(words[words.length - 1]!)) suffix = ` ${words.pop()!.toUpperCase()}`;
  const significant = words.filter((word) => !SMALL_WORDS.has(word.toLowerCase()));
  const word = significant[0] ?? words[0] ?? trimmed;
  const initials = significant.slice(0, 4).map((part) => part[0]!.toUpperCase()).join("");
  const base = significant.length >= 2 && !AWKWARD_INITIALS.has(initials) ? initials : shortWord(word);
  return `${base}${suffix}`;
}

/** The longest short name a class can be given: what fits a chip beside a session's name. */
export const SHORT_NAME_MAX = 10;

/** A short name as it is stored: capitals, letters and digits with single spaces, at most SHORT_NAME_MAX long. */
export function normalizeShortName(text: string): string {
  return text.toUpperCase().replace(/[^A-Z0-9 ]+/g, " ").replace(/\s+/g, " ").trim().slice(0, SHORT_NAME_MAX).trim();
}

/** A class's tag: the short name the student gave it, otherwise one made from its name (courseShortName). */
export function classShortName(cls: { name: string; shortName?: string } | null | undefined, fallbackName = ""): string {
  const own = cls?.shortName ? normalizeShortName(cls.shortName) : "";
  return own || courseShortName(cls?.name ?? fallbackName);
}

/**
 * The short name offered when a class is made from a syllabus: the letters of its course code ("FINC 3100" ->
 * "FINC"), or with no code what courseShortName makes of the name. When another class already uses that tag, the
 * longer form is offered instead ("FINC 3200"), so two classes of one subject can be told apart.
 */
export function suggestShortName(input: { name: string; code?: string; taken?: readonly string[] }): string {
  const taken = new Set((input.taken ?? []).map((tag) => normalizeShortName(tag)));
  const code = (input.code ?? "").trim();
  const letters = /^[A-Za-z]{2,5}(?![A-Za-z])/.exec(code)?.[0]?.toUpperCase() ?? "";
  if (letters && !taken.has(letters)) return letters;
  // The longer form: the code with its number ("FINC 3200") when it is a course code; what the name alone gives
  // when the "code" is a long word or has no letters at all.
  return normalizeShortName(courseShortName(letters ? `${code} ${input.name}` : input.name));
}

/**
 * The class a task belongs to: by its id, or, when that id has gone stale (the class was made again), by its name.
 * Every place that shows a task's class tag asks here, so they cannot disagree.
 */
export function classOfTask<T extends { id: string; name: string }>(task: { courseId?: string; courseName?: string }, classes: readonly T[]): T | undefined {
  return (task.courseId ? classes.find((cls) => cls.id === task.courseId) : undefined) ?? (task.courseName ? classes.find((cls) => cls.name === task.courseName) : undefined);
}

export interface CourseContext {
  classes: ReadonlyArray<{ id: string; name: string; shortName?: string }>;
  tasks: ReadonlyArray<{ id: string; courseId: string; courseName: string }>;
}

/** Short course label of a block (class meetings by courseId, study sessions through their task), or undefined. */
export function blockCourseLabel(block: Pick<ScheduleBlock, "courseId" | "taskId">, context: CourseContext): string | undefined {
  const classById = (id: string | undefined) => (id ? context.classes.find((cls) => cls.id === id) : undefined);
  const direct = classById(block.courseId);
  if (direct) return classShortName(direct) || undefined;
  const task = block.taskId ? context.tasks.find((candidate) => candidate.id === block.taskId) : undefined;
  if (!task) return undefined;
  return classShortName(classOfTask(task, context.classes), task.courseName) || undefined;
}

const VERB_PREFIX = /^(?:Study|Work on|Draft|Review|Finalize|Practice Test|Catch up):\s*/i;

/** Block title without the generated verb prefix ("Work on: Essay (1/2)" -> "Essay (1/2)"). */
export function blockDisplayTitle(title: string): string {
  const stripped = title.replace(VERB_PREFIX, "").trim();
  return stripped || title;
}

/**
 * A session's name where its class is already shown beside it (a tag, a colour bar): the generated verb prefix goes
 * (blockDisplayTitle), and so does a leading class name ("Study: Principles of Finance exam prep — Learn: Topic 3"
 * -> "Exam prep — Learn: Topic 3"). A title that is only the class name is left alone.
 */
export function sessionDisplayTitle(title: string, courseName?: string): string {
  const base = blockDisplayTitle(title);
  const course = courseName?.trim();
  if (!course || course === "General") return base;
  if (base.length <= course.length || !base.toLowerCase().startsWith(course.toLowerCase())) return base;
  const rest = base.slice(course.length).replace(/^[\s:·–—-]+/, "").trim();
  return rest ? rest[0]!.toUpperCase() + rest.slice(1) : base;
}

