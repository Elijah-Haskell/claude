export interface TimeSpan {
  startTime: string;
  /** "24:00" = the end of the day. */
  endTime: string;
}

type TimedEvent = Pick<GoogleCalendarEventLocal, "isAllDay" | "startDate" | "endDate" | "startTime" | "endTime" | "status">;

/** First and last day of an event (an end date before the start reads as the start). */
function eventDays(event: Pick<GoogleCalendarEventLocal, "startDate" | "endDate">): { startDate: string; endDate: string } {
  const startDate = event.startDate.slice(0, 10);
  const rawEnd = (event.endDate ?? event.startDate).slice(0, 10);
  return { startDate, endDate: rawEnd > startDate ? rawEnd : startDate };
}

/** End of a timed event as "HH:MM" (a missing end time means an hour). */
function eventEndClock(event: Pick<GoogleCalendarEventLocal, "startTime" | "endTime">): string {
  return event.endTime ?? minutesToTime((timeToMinutes(event.startTime ?? "00:00") + 60) % MINUTES_PER_DAY);
}

/**
 * The part of a timed calendar event that falls on `dateKey`, or null. An event over several days (Fri 22:00 to
 * Sat 02:00) is drawn on every day it covers, the way the planner keeps study off it (lib/busy-windows.ts): the tail
 * of the first day, whole days in between and the head of the last day. All-day events are not timed (null).
 */
export function timedEventSpanOn(event: TimedEvent, dateKey: string): TimeSpan | null {
  if (event.isAllDay || !event.startTime || event.status === "cancelled") return null;
  const { startDate, endDate } = eventDays(event);
  if (dateKey < startDate || dateKey > endDate) return null;
  const start = timeToMinutes(event.startTime);
  const end = event.endTime ? timeToMinutes(event.endTime) : start + 60;
  const clock = (minutes: number) => (minutes >= MINUTES_PER_DAY ? "24:00" : minutesToTime(minutes));
  if (startDate === endDate) return { startTime: event.startTime, endTime: end > start ? clock(end) : "24:00" };
  if (dateKey === startDate) return { startTime: event.startTime, endTime: "24:00" };
  if (dateKey === endDate) return end > 0 ? { startTime: "00:00", endTime: clock(end) } : null;
  return { startTime: "00:00", endTime: "24:00" };
}

/** "7:00 PM – 9:00 PM", "10:00 PM Fri – 2:00 AM Sat" for an event that runs into another day, or "All day". */
export function calendarEventTimeLabel(event: TimedEvent): string {
  if (event.isAllDay || !event.startTime) return "All day";
  const { startDate, endDate } = eventDays(event);
  const end = formatTime(eventEndClock(event));
  return endDate > startDate
    ? `${formatTime(event.startTime)} ${weekdayOfKey(startDate)} – ${end} ${weekdayOfKey(endDate)}`
    : `${formatTime(event.startTime)} – ${end}`;
}

/** What a screen reader says: "Calendar: Team dinner, Friday 7 to 9 PM" (with both days when it runs into another). */
export function describeCalendarEventForA11y(event: TimedEvent & Pick<GoogleCalendarEventLocal, "title" | "source">): string {
  const { startDate, endDate } = eventDays(event);
  const head = `${calendarSourceLabel(event)}: ${event.title}`;
  if (event.isAllDay || !event.startTime) return `${head}, all day, ${weekdayName(startDate)}`;
  const end = eventEndClock(event);
  if (endDate > startDate) {
    return `${head}, ${weekdayName(startDate)} ${spokenClock(timeToMinutes(event.startTime), true)} to ${weekdayName(endDate)} ${spokenClock(timeToMinutes(end), true)}`;
  }
  return `${head}, ${weekdayName(startDate)} ${spokenTimeRange(event.startTime, end)}`;
}

// ── All-day calendar events ───────────────────────────────────

/**
 * Does an all-day event cover `dateKey`? Google's all-day `endDate` is exclusive (a one-day event has
 * endDate = startDate + 1), so a 3-day trip covers exactly 3 days.
 */
export function allDayEventCovers(event: { startDate: string; endDate?: string }, dateKey: string): boolean {
  const start = event.startDate.slice(0, 10);
  const endRaw = (event.endDate ?? start).slice(0, 10);
  const lastDay = endRaw > start ? addDaysToKey(endRaw, -1) : start;
  return dateKey >= start && dateKey <= lastDay;
}

// ── Week navigation and small summaries ───────────────────────

/** The 7 date keys (Mon..Sun) of the week that starts on `weekStartKey`. */
export function weekDateKeys(weekStartKey: string): string[] {
  return Array.from({ length: 7 }, (_, index) => addDaysToKey(weekStartKey, index));
}

/** Monday key of the week `offset` weeks away from the week containing `todayKey`. */
export function weekStartForOffset(todayKey: string, offset: number): string {
  return addDaysToKey(weekStartKeyOf(todayKey), offset * 7);
}

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

function shortDate(key: string): string {
  const [, month, day] = key.split("-").map(Number);
  return `${MONTHS[(month ?? 1) - 1] ?? ""} ${day ?? ""}`;
}

/** "Sep 21 – Sep 27" for the week starting on `weekStartKey`. */
export function formatWeekRange(weekStartKey: string): string {
  return `${shortDate(weekStartKey)} – ${shortDate(addDaysToKey(weekStartKey, 6))}`;
}

/**
 * Date the "+" button pre-fills: today when the viewed week contains it, the week's first day when it is
 * still ahead, and today when the viewed week is already in the past (never a day that is gone).
 */
export function defaultAddDate(weekStartKey: string, todayKey: string): string {
  const weekEndKey = addDaysToKey(weekStartKey, 6);
  if (todayKey >= weekStartKey && todayKey <= weekEndKey) return todayKey;
  return weekStartKey > todayKey ? weekStartKey : todayKey;
}

export interface WeekSummary {
  totalBlocks: number;
  studyBlocks: number;
  studyHours: number;
  classBlocks: number;
  freeBlocks: number;
  tasksScheduled: number;
  peakStudyDay: string;
}

/** Numbers for the "your plan is ready" card, from the blocks of one week (what the grid draws: no sleep, no transitions). */
export function summarizeWeek(blocks: readonly ScheduleBlock[]): WeekSummary {
  const minutes = (block: ScheduleBlock) => Math.max(0, timeToMinutes(block.endTime) - timeToMinutes(block.startTime));
  const study = blocks.filter((block) => block.type === "study" && block.completionStatus !== "skipped" && block.completionStatus !== "missed");
  const studyMinutesByDate: Record<string, number> = {};
  for (const block of study) studyMinutesByDate[block.date] = (studyMinutesByDate[block.date] ?? 0) + minutes(block);
  let peakDate = "";
  let peakMinutes = 0;
  for (const date of Object.keys(studyMinutesByDate).sort()) {
    if (studyMinutesByDate[date]! > peakMinutes) {
      peakMinutes = studyMinutesByDate[date]!;
      peakDate = date;
    }
  }
  return {
    totalBlocks: blocks.filter(showsOnWeekGrid).length,
    studyBlocks: study.length,
    studyHours: study.reduce((sum, block) => sum + minutes(block), 0) / 60,
    classBlocks: blocks.filter((block) => block.type === "class").length,
    freeBlocks: blocks.filter((block) => block.type === "free").length,
    tasksScheduled: new Set(study.flatMap((block) => (block.taskId ? [block.taskId] : []))).size,
    peakStudyDay: peakDate ? weekdayName(peakDate) : "",
  };
}
