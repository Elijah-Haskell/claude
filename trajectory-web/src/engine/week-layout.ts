function spokenClock(minutes: number, withPeriod: boolean): string {
  const h = Math.floor(minutes / 60) % 24;
  const m = minutes % 60;
  const hour = h % 12 || 12;
  const clock = m === 0 ? `${hour}` : `${hour}:${String(m).padStart(2, "0")}`;
  return withPeriod ? `${clock} ${h < 12 ? "AM" : "PM"}` : clock;
}

/** "3 to 4 PM", "11 AM to 1 PM", "9:30 to 10:45 AM". */
export function spokenTimeRange(startTime: string, endTime: string): string {
  const start = timeToMinutes(startTime);
  const end = timeToMinutes(endTime);
  const isMorning = (minutes: number) => Math.floor(minutes / 60) % 24 < 12;
  const samePeriod = isMorning(start) === isMorning(end);
  return `${spokenClock(start, !samePeriod)} to ${spokenClock(end, true)}`;
}

/**
 * What a screen reader says for a block: "Study: Chem exam prep, Tuesday 3 to 4 PM, flexible".
 * `courseLabel` (e.g. "CHEM 101") is added for study sessions so the course is heard, not just seen.
 * Flexible = the plan may still move it; kept = the student kept it (it stays when the plan changes).
 */
export function describeBlockForA11y(
  block: Pick<ScheduleBlock, "type" | "title" | "date" | "startTime" | "endTime" | "accepted" | "locked" | "completionStatus">,
  courseLabel?: string,
): string {
  const title = block.type === "study" ? blockDisplayTitle(block.title) : block.title;
  const course = courseLabel && block.type === "study" && !title.toLowerCase().includes(courseLabel.toLowerCase()) ? ` (${courseLabel})` : "";
  const parts = [`${blockTypeLabel(block.type)}: ${title}${course}`, `${weekdayName(block.date)} ${spokenTimeRange(block.startTime, block.endTime)}`];
  if (block.completionStatus === "done") parts.push("done");
  else if (block.completionStatus === "skipped") parts.push("skipped");
  else if (block.completionStatus === "missed") parts.push("missed");
  else if (!block.accepted) parts.push("flexible");
  else if (block.type === "study") parts.push("kept");
  if (block.locked && block.type !== "class") parts.push("never moves");
  return parts.join(", ");
}

/**
 * Options for a minute wheel that offers `grid` (e.g. 0, 5, 10 ... 55). A stored time can be off that grid
 * (09:07, from a syllabus or an earlier edit): keep that minute in the list so it stays visible and
 * selectable instead of silently snapping to another minute.
 */
export function minuteWheelOptions(current: number, grid: readonly number[]): number[] {
  return grid.includes(current) ? [...grid] : [...grid, current].sort((a, b) => a - b);
}

